const TABLES = { uz, ru, en };

/** `verifyTexts(language)(key, vars)` — `{name}` o'rinlari `vars` bilan to'ldiriladi. */
export default function verifyTexts(language) {
  const table = TABLES[language] ?? uz;
  return (key, vars) => {
    let text = table[key] ?? uz[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    return text;
  };
}
